-- T5 owns Placement authority and delivery. Full approval workflow remains its later task.
CREATE TABLE placements (
 id VARCHAR(36) NOT NULL PRIMARY KEY,
 student_user_id VARCHAR(36) NOT NULL,
 school_org_id VARCHAR(36) NOT NULL,
 enterprise_org_id VARCHAR(36) NOT NULL,
 term_id VARCHAR(36) NOT NULL,
 demand_id VARCHAR(36) NOT NULL,
 cooperation_id VARCHAR(36) NOT NULL,
 proposal_item_id VARCHAR(36) NOT NULL,
 state VARCHAR(32) NOT NULL,
 version BIGINT NOT NULL,
 effective_at DATETIME(6) NOT NULL,
 start_date DATE NOT NULL,
 end_date DATE NOT NULL,
 approved_at DATETIME(6) NULL,
 cancelled_at DATETIME(6) NULL,
 completed_at DATETIME(6) NULL,
 decision_ref VARCHAR(120) NULL,
 FOREIGN KEY(student_user_id) REFERENCES users(id),
 FOREIGN KEY(term_id,school_org_id) REFERENCES terms(id,school_org_id),
 FOREIGN KEY(enterprise_org_id) REFERENCES organizations(id),
 CHECK(state IN ('PENDING_APPROVAL','APPROVED','ACTIVE','CANCELLED','COMPLETED')),
 CHECK(version BETWEEN 1 AND 9007199254740991),
 CHECK(start_date<=end_date),
 CHECK(state NOT IN ('APPROVED','ACTIVE','COMPLETED') OR approved_at IS NOT NULL),
 CHECK(state<>'CANCELLED' OR cancelled_at IS NOT NULL),
 CHECK(state<>'COMPLETED' OR completed_at IS NOT NULL),
 INDEX ix_placement_scope(enterprise_org_id,school_org_id,term_id,state)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE placement_outbox (
 event_id VARCHAR(36) NOT NULL PRIMARY KEY,
 delivery_operation_id VARCHAR(36) NOT NULL UNIQUE,
 placement_id VARCHAR(36) NOT NULL,
 aggregate_version BIGINT NOT NULL,
 event_type VARCHAR(32) NOT NULL,
 payload_json JSON NOT NULL,
 state VARCHAR(16) NOT NULL DEFAULT 'PENDING',
 attempt_count INT NOT NULL DEFAULT 0,
 next_attempt_at DATETIME(6) NOT NULL,
 last_reason VARCHAR(32) NULL,
 created_at DATETIME(6) NOT NULL,
 UNIQUE(placement_id,aggregate_version,event_type),
 FOREIGN KEY(placement_id) REFERENCES placements(id),
 CHECK(state IN ('PENDING','DONE','DLQ')),
 CHECK(attempt_count BETWEEN 0 AND 5),
 INDEX ix_placement_delivery(state,next_attempt_at,event_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
