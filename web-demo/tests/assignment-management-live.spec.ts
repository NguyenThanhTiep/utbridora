import { test, expect, type Page } from '@playwright/test';
import { openWorkspacePage } from './helpers/workspace';

test('school confirms coordinator, coordinator grants HR, HR hands over and school revokes the root', async ({ browser }) => {
  test.skip(!process.env.E2E_ASSIGNMENT_MANAGEMENT, 'Run through AssignmentManagementIT with isolated MySQL');
  test.setTimeout(180000);
  const cfg = JSON.parse(process.env.E2E_ASSIGNMENT_MANAGEMENT!) as Record<string, string>;
  const signIn = async (page: Page, email: string) => {
    await page.getByLabel('Email', { exact: true }).fill(email);
    await page.getByLabel('Mật khẩu', { exact: true }).fill(cfg.password);
    await page.getByRole('button', { name: 'Đăng nhập', exact: true }).click();
    await expect(page.locator('.workspace')).toBeVisible();
  };
  const actor = async (email: string) => {
    const context = await browser.newContext({ reducedMotion: 'reduce' });
    const page = await context.newPage(); await page.goto('/'); await signIn(page, email);
    return { context, page };
  };
  const school = await actor(cfg.staffEmail);
  await openWorkspacePage(school.page, 'Phân công thực tập');
  await school.page.getByLabel('Doanh nghiệp', { exact: true }).selectOption(cfg.enterpriseId);
  await school.page.getByLabel('Người nhận Coordinator', { exact: true }).selectOption(cfg.coordinatorId);
  await school.page.getByLabel('Căn cứ quyết định', { exact: true }).fill('BROWSER-COORDINATOR');
  await school.page.getByRole('button', { name: 'Xác nhận Coordinator', exact: true }).click();
  await expect(school.page.getByText('Đã xác nhận Coordinator. Người nhận cần đăng nhập lại để cập nhật quyền.', { exact: true })).toBeVisible();
  const coordinator = await actor(cfg.coordinatorEmail);
  await openWorkspacePage(coordinator.page, 'Phân công thực tập');
  await coordinator.page.getByLabel('Người nhận HR', { exact: true }).selectOption(cfg.hrId);
  await coordinator.page.getByLabel('Căn cứ quyết định', { exact: true }).fill('BROWSER-HR');
  await coordinator.page.getByRole('button', { name: 'Cấp phân công HR', exact: true }).click();
  await expect(coordinator.page.getByText('Đã cấp phân công HR. Người nhận cần đăng nhập lại để cập nhật quyền.', { exact: true })).toBeVisible();
  const hr = await actor(cfg.hrEmail);
  await openWorkspacePage(hr.page, 'Phân công thực tập');
  await hr.page.getByLabel('Hồ sơ cần bàn giao', { exact: true }).selectOption(cfg.caseId);
  await hr.page.getByLabel('Mentor tiếp nhận', { exact: true }).selectOption(cfg.mentorId);
  await hr.page.getByLabel('Mã lý do bàn giao', { exact: true }).fill('MENTOR_HANDOVER');
  await hr.page.getByRole('button', { name: 'Xác nhận bàn giao Mentor', exact: true }).click();
  await expect(hr.page.getByText('Đã ghi nhận bàn giao Mentor. Mentor cần đăng nhập lại để cập nhật quyền.', { exact: true })).toBeVisible();
  await hr.page.setViewportSize({ width: 390, height: 844 });
  await expect.poll(() => hr.page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await hr.page.screenshot({ path: '../target/assignment-management-mobile.png', fullPage: true });
  await school.page.reload(); await openWorkspacePage(school.page, 'Phân công thực tập');
  await school.page.getByLabel('Doanh nghiệp', { exact: true }).selectOption(cfg.enterpriseId);
  const row = school.page.getByRole('row').filter({ hasText: 'New coordinator' });
  await row.getByRole('button', { name: 'Chi tiết phân công', exact: true }).click();
  await expect(school.page.getByRole('region', { name: 'Chi tiết phân công' })).toContainText('BROWSER-COORDINATOR');
  await school.page.getByLabel('Mã lý do thu hồi', { exact: true }).fill('TEAM_CHANGED');
  await expect(school.page.getByRole('button', { name: 'Thu hồi phân công', exact: true })).toBeDisabled();
  await school.page.getByRole('checkbox', { name: 'Tôi xác nhận thu hồi và hiểu ảnh hưởng tới quyền phụ thuộc.', exact: true }).check();
  await school.page.getByRole('button', { name: 'Thu hồi phân công', exact: true }).click();
  await expect(school.page.getByText('Đã thu hồi phân công. Quyền phụ thuộc được kiểm tra lại; người bị ảnh hưởng cần đăng nhập lại.', { exact: true })).toBeVisible();
  expect((await coordinator.page.request.get('/api/v1/t3/context-assignments/me')).status()).toBe(401);
  expect((await hr.page.request.get('/api/v1/t3/context-assignments/me')).status()).toBe(401);
  await hr.page.reload(); await signIn(hr.page, cfg.hrEmail);
  await openWorkspacePage(hr.page, 'Phân công thực tập');
  await expect(hr.page.getByText('Chưa có phạm vi cấp quyền phù hợp', { exact: true })).toBeVisible();
  await school.page.getByRole('checkbox', { name: 'Bao gồm phân công đã thu hồi', exact: true }).check();
  await expect(school.page.getByRole('row').filter({ hasText: 'New coordinator' })).toContainText('Đã thu hồi');
  await school.page.screenshot({ path: '../target/assignment-management-revoked.png', fullPage: true });
  await school.context.close(); await coordinator.context.close(); await hr.context.close();
});
