import { test, expect, type Browser, type Page } from '@playwright/test';

test('admin bootstrap, school subdelegation and revocation use real APIs and current sessions', async ({ browser }) => {
  test.skip(process.env.E2E_DELEGATIONS !== 'true', 'Run through SchoolDelegationManagementIT on isolated MySQL');
  test.setTimeout(150000);
  const signIn = async (page: Page, email: string) => {
    await page.getByLabel('Email', { exact: true }).fill(email);
    await page.getByLabel('Mật khẩu', { exact: true }).fill(email === 'admin@example.test' ? process.env.E2E_ADMIN_PASSWORD! : process.env.E2E_PASSWORD!);
    await page.getByRole('button', { name: 'Đăng nhập', exact: true }).click();
    await expect(page.getByRole('heading', { name: 'Tài khoản của tôi', exact: true })).toBeVisible();
  };
  const actor = async (browser: Browser, email: string) => { const context = await browser.newContext({ reducedMotion: 'reduce' }); const page = await context.newPage(); await page.goto('/'); await signIn(page, email); return { context, page }; };
  const admin = await actor(browser, 'admin@example.test'), school = await actor(browser, 'school@example.test'), reviewer = await actor(browser, 'delegate@example.test');
  const schoolHeaders = { 'X-Organization-Id': '00000000-0000-4000-8000-000000000011' };
  expect((await reviewer.page.request.get('/api/v1/school/cooperations', { headers: schoolHeaders })).status()).toBe(404);
  await admin.page.getByRole('button', { name: 'Phân công quyền cán bộ', exact: true }).click();
  await expect(admin.page.getByRole('heading', { name: 'Khởi tạo phân công demo', exact: true })).toBeVisible();
  await admin.page.getByLabel('Tìm cán bộ theo tên hoặc email', { exact: true }).fill('school@example.test');
  await admin.page.getByRole('combobox', { name: 'Cán bộ nhận quyền', exact: true }).selectOption('00000000-0000-4000-8000-000000000002');
  await admin.page.getByRole('checkbox', { name: 'Quản lý phân công quyền cán bộ', exact: true }).check();
  await admin.page.getByRole('checkbox', { name: 'Xét duyệt hợp tác được phân công', exact: true }).check();
  await admin.page.getByLabel('Căn cứ phân công', { exact: true }).fill('DEMO-BROWSER-DELEGATION-ROOT');
  await admin.page.getByRole('button', { name: 'Cấp phân công', exact: true }).click();
  await expect(admin.page.getByText('Đã cấp phân công. Cán bộ nhận quyền cần đăng nhập lại.', { exact: true })).toBeVisible();
  await expect(admin.page.getByRole('region', { name: 'Chi tiết phân công' })).toContainText('DEMO-BROWSER-DELEGATION-ROOT');
  await expect(admin.page.locator('.loading-state')).toHaveCount(0);
  await admin.page.screenshot({ path: '../target/delegations-browser-admin.png', fullPage: true });
  await school.page.reload(); await signIn(school.page, 'school@example.test');
  await school.page.getByRole('button', { name: 'Phân công quyền cán bộ', exact: true }).click();
  await expect(school.page.getByRole('heading', { name: 'Cấp phân công nghiệp vụ', exact: true })).toBeVisible();
  await school.page.getByLabel('Tìm cán bộ theo tên hoặc email', { exact: true }).fill('delegate@example.test');
  await school.page.getByRole('combobox', { name: 'Cán bộ nhận quyền', exact: true }).selectOption('00000000-0000-4000-8000-000000000201');
  await expect(school.page.getByRole('checkbox', { name: 'Quản lý tiếp nhận theo thẩm quyền', exact: true })).toHaveCount(0);
  await school.page.getByRole('checkbox', { name: 'Xét duyệt hợp tác được phân công', exact: true }).check();
  await school.page.getByLabel('Căn cứ phân công', { exact: true }).fill('BROWSER-SCHOOL-CHILD');
  await school.page.getByRole('button', { name: 'Cấp phân công', exact: true }).click();
  await expect(school.page.getByText('Đã cấp phân công. Cán bộ nhận quyền cần đăng nhập lại.', { exact: true })).toBeVisible();
  await expect(school.page.locator('.loading-state')).toHaveCount(0);
  await school.page.setViewportSize({ width: 390, height: 844 });
  await expect.poll(() => school.page.locator('aside.sidebar').evaluate(element => element.getBoundingClientRect().right)).toBeLessThanOrEqual(0);
  await school.page.screenshot({ path: '../target/delegations-browser-mobile.png', fullPage: true });
  expect(await school.page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await reviewer.page.reload(); await signIn(reviewer.page, 'delegate@example.test');
  const visible = await reviewer.page.request.get('/api/v1/school/cooperations', { headers: schoolHeaders });
  expect(visible.status(), await visible.text()).toBe(200);
  await reviewer.page.getByRole('button', { name: 'Hợp tác doanh nghiệp', exact: true }).click();
  await expect(reviewer.page.getByRole('heading', { name: 'Đề nghị 1 · Đã gửi', exact: true })).toBeVisible();
  await reviewer.page.reload(); await reviewer.page.getByRole('button', { name: 'Hợp tác doanh nghiệp', exact: true }).click();
  await expect(reviewer.page.getByRole('heading', { name: 'Đề nghị 1 · Đã gửi', exact: true })).toBeVisible();
  await admin.page.getByRole('button', { name: 'Thu hồi phân công', exact: true }).click();
  await expect(admin.page.getByText('Đã thu hồi phân công và các phiên bị ảnh hưởng.', { exact: true })).toBeVisible();
  await expect(admin.page.getByRole('region', { name: 'Chi tiết phân công' })).toContainText('Đã thu hồi');
  expect((await reviewer.page.request.get('/api/v1/school/cooperations', { headers: schoolHeaders })).status()).toBe(401);
  await reviewer.page.reload(); await signIn(reviewer.page, 'delegate@example.test');
  expect((await reviewer.page.request.get('/api/v1/school/cooperations', { headers: schoolHeaders })).status()).toBe(404);
  await school.page.reload(); await signIn(school.page, 'school@example.test');
  await school.page.getByRole('button', { name: 'Mở menu điều hướng', exact: true }).click();
  await school.page.getByRole('button', { name: 'Phân công quyền cán bộ', exact: true }).click();
  await expect(school.page.getByRole('heading', { name: 'Chưa có kỳ được quản lý', exact: true })).toBeVisible();
  await Promise.all([admin.context.close(), school.context.close(), reviewer.context.close()]);
});
